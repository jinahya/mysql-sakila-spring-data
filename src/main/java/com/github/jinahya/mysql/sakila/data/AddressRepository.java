package com.github.jinahya.mysql.sakila.data;

import com.github.jinahya.mysql.sakila.persistence.Address;
import com.github.jinahya.mysql.sakila.persistence.Address_;
import com.github.jinahya.mysql.sakila.persistence.City_;
import com.github.jinahya.mysql.sakila.persistence.Customer;
import com.github.jinahya.mysql.sakila.persistence.Customer_;
import com.github.jinahya.mysql.sakila.persistence.Staff;
import com.github.jinahya.mysql.sakila.persistence.Staff_;
import com.github.jinahya.mysql.sakila.persistence.Store;
import com.github.jinahya.mysql.sakila.persistence.Store_;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.domain.Specification;
import org.springframework.data.jpa.repository.NativeQuery;
import org.springframework.data.jpa.repository.Query;
import org.springframework.stereotype.Repository;

import java.util.List;
import java.util.Objects;
import java.util.stream.Stream;

/**
 * A repository for {@link Address}, the {@code address} table of the Sakila database.
 * <p>
 * The id is an {@link Integer} generated by the database ({@code GenerationType.IDENTITY}), so a newly constructed
 * address is saved with no id, and the id is set on the saved instance. An address has no business key:
 * {@link Address#equals(Object)} compares ids, and only once they are assigned. Each address is in a city
 * ({@link Address_#CITY}), and the city in a country; customers, staff members and stores each refer to an address, but
 * an address does not map them back.
 * <p>
 * {@link _Repository} brings {@link org.springframework.data.jpa.repository.JpaSpecificationExecutor} for criteria
 * queries. Name the attributes through the generated static metamodel rather than by string, for example
 * {@code (root, query, builder) -> builder.equal(root.get(Address_.district), district)}.
 * <p>
 * {@link Address} declares named queries too ({@code Address.selectOneByAddressId},
 * {@code Address.selectListOrderByAddressIdAsc}, {@code Address.selectListByCityOrderByAddressIdAsc}, ...), but no
 * method here runs them yet.
 * <p>
 * The methods below answer the exercises of upstream's {@code EXERCISES.asciidoc} on the {@code address} table, one
 * method per exercise, named in each method's javadoc by the exercise's id ({@code SAKILA-ADDRESS-B-03}, ...), with its
 * role: the book's pick, this module's own extra, or native-only. The exercises are context, not contract. A Basic
 * exercise is a derived query, with the order the exercise asks for in its name, and returns a {@link List} (the
 * book's pick) or a {@link Stream} (this module's own extra), with no {@link Pageable}. An Intermediate or Advanced
 * one takes a {@link Pageable}, the page and the sort, and returns a {@link Page}, so the order the exercise asks for,
 * and its {@code LIMIT}, are the caller's {@code PageRequest}; each method's javadoc says which sort that is. An
 * exercise that shows rows of addresses is a {@code default} method, {@code list...}, which builds a
 * {@link Specification} with the Criteria API and runs it through
 * {@link org.springframework.data.jpa.repository.JpaSpecificationExecutor}. An exercise that shows columns, grouped
 * and counted, or paired, cannot be a {@code Specification}, which only filters rows of one entity; such a method,
 * {@code select...}, declares its JPQL with {@link Query}, with a count query of its own, and returns a projection, one
 * of the interfaces declared here, which Spring Data backs with the selected columns, each aliased with the name of
 * the getter it feeds. Those aliases are what the {@code Pageable} sorts by. A native-only exercise, a top-N per group
 * by a window function, is a {@link NativeQuery} with the exercise's SQL.
 *
 * @see Address
 * @see Address_
 */
@Repository
public interface AddressRepository
        extends _Repository<Address, Integer> {

    // ----------------------------------------------------------------------------------------------------- exercises

    /**
     * A district, and in how many countries an address of that district is: a projection of
     * {@link #selectDistrictsInMoreCountriesThan(long, Pageable)}, sortable by {@code district} and {@code countries}.
     */
    interface DistrictCountryCount {

        /**
         * Returns the name of the district.
         *
         * @return the name of the district.
         */
        String getDistrict();

        /**
         * Returns the number of countries the addresses of the district are in.
         *
         * @return the number of countries.
         */
        long getCountries();
    }

    /**
     * Two addresses which share a postal code: a projection of {@link #selectPairsSharingPostalCode(Pageable)},
     * sortable by {@code addressId}, {@code address}, {@code otherAddressId}, {@code otherAddress} and
     * {@code postalCode}.
     */
    interface AddressPair {

        /**
         * Returns the id of the address of the lower id.
         *
         * @return the id of the first address.
         */
        Integer getAddressId();

        /**
         * Returns the address of the lower id.
         *
         * @return the first address.
         */
        String getAddress();

        /**
         * Returns the id of the address of the higher id.
         *
         * @return the id of the other address.
         */
        Integer getOtherAddressId();

        /**
         * Returns the address of the higher id.
         *
         * @return the other address.
         */
        String getOtherAddress();

        /**
         * Returns the postal code the two addresses share.
         *
         * @return the postal code.
         */
        String getPostalCode();
    }

    /**
     * A country, a district of it, and how many addresses the district has: a projection of
     * {@link #selectTopThreeDistrictsOfIndiaChinaAndUnitedStates()}.
     */
    interface CountryDistrictCount {

        /**
         * Returns the name of the country.
         *
         * @return the name of the country.
         */
        String getCountry();

        /**
         * Returns the name of the district.
         *
         * @return the name of the district.
         */
        String getDistrict();

        /**
         * Returns the number of addresses of the district, in the country.
         *
         * @return the number of addresses.
         */
        long getAddresses();
    }

    /**
     * Finds the addresses whose value of {@link Address_#ADDRESS2} attribute is {@code null}, by
     * {@link Address_#ADDRESS_ID} ({@code SAKILA-ADDRESS-B-03}, the book's pick, which orders by
     * {@link Address_#ADDRESS_ID}).
     * <p>
     * The query, and its order, are derived from the method name; {@code IsNull} is {@code IS NULL}, not
     * {@code = NULL}, which would match nothing. An empty {@code address2} is not {@code null}, and not found.
     *
     * @return a list of the addresses with no {@code address2}, by id; empty if there is none.
     */
    List<Address> findAllByAddress2IsNullOrderByAddressIdAsc();

    /**
     * Finds the addresses whose value of {@link Address_#DISTRICT} attribute is equal to the specified value, as a
     * stream, by {@link Address_#ADDRESS_ID} ({@code SAKILA-ADDRESS-B-04}, this module's own extra, which finds the
     * addresses with an empty district, {@code ""}, and orders by {@link Address_#ADDRESS_ID}).
     * <p>
     * The query, and its order, are derived from the method name. The stream is to be consumed inside a transaction
     * the caller opened, and closed, in a try-with-resources; outside one, Spring Data refuses the call with an
     * {@link org.springframework.dao.InvalidDataAccessApiUsageException}, before any query runs.
     *
     * @param district the value of the {@link Address_#DISTRICT} attribute to match; {@code ""} for the exercise; must
     *                 not be {@code null}.
     * @return a stream of the addresses whose district is {@code district}, by id, to be closed by the caller; empty if
     *         there is none.
     */
    Stream<Address> findAllByDistrictOrderByAddressIdAsc(String district);

    /**
     * Lists the addresses, each with its city and the city's country fetched ({@code SAKILA-ADDRESS-I-01}, the book's
     * pick, which takes the first five by {@link Address_#ADDRESS_ID}).
     * <p>
     * A {@link Specification} with no filter, which fetch-joins the {@link Address_#CITY} of each address and the
     * {@link City_#COUNTRY} of that city, so that the city and the country names the exercise shows are loaded with the
     * address, and readable after the method returns. Spring Data runs the same specification for the count query, in
     * which a fetch join is an error; the fetch joins are added only when the query is not that count.
     *
     * @param pageable the page to return, and its sort; must not be {@code null}.
     * @return a page of the addresses, their cities and countries fetched.
     */
    default Page<Address> listWithCityAndCountry(final Pageable pageable) {
        Objects.requireNonNull(pageable, "pageable is null");
        final Specification<Address> specification = (r, q, b) -> {
            if (!Long.class.equals(Objects.requireNonNull(q).getResultType())) {
                r.fetch(Address_.city).fetch(City_.country);
            }
            return b.conjunction();
        };
        return findAll(specification, pageable);
    }

    /**
     * Selects the districts whose addresses are in more than the specified number of countries, with those numbers
     * ({@code SAKILA-ADDRESS-I-02}, this module's own extra, which takes the districts in more than one country, and
     * orders by {@code countries} descending, then by {@code district}).
     * <p>
     * The addresses with a name of a district, not an empty one, are grouped by district, and the distinct countries
     * of their cities counted; the filter is on the groups, so it is a {@code HAVING}, which a {@link Specification},
     * which filters rows, cannot do. The count query counts the districts that pass the same {@code HAVING}, through a
     * subquery.
     *
     * @param countries the number of countries a district has to be in more than.
     * @param pageable  the page to return, and its sort, by {@code district} or {@code countries}; must not be
     *                  {@code null}.
     * @return a page of the districts in more than {@code countries} countries, with their numbers of countries.
     */
    @Query(value = """
            SELECT a.district AS district, COUNT(DISTINCT ci.country) AS countries
            FROM Address a
                     JOIN a.city ci
            WHERE a.district <> ''
            GROUP BY a.district
            HAVING COUNT(DISTINCT ci.country) > :countries""",
           countQuery = """
                   SELECT COUNT(DISTINCT a.district)
                   FROM Address a
                   WHERE a.district IN (SELECT a2.district
                                        FROM Address a2
                                                 JOIN a2.city ci2
                                        WHERE a2.district <> ''
                                        GROUP BY a2.district
                                        HAVING COUNT(DISTINCT ci2.country) > :countries)""")
    Page<DistrictCountryCount> selectDistrictsInMoreCountriesThan(long countries, Pageable pageable);

    /**
     * Lists the addresses no customer, staff member or store has ({@code SAKILA-ADDRESS-A-01}, the book's pick, which
     * orders by {@link Address_#ADDRESS_ID}).
     * <p>
     * An address does not map the entities that refer to it, so a {@link Specification} of three {@code NOT EXISTS}
     * subqueries asks each of them, by {@link Customer_#ADDRESS}, {@link Staff_#ADDRESS} and {@link Store_#ADDRESS}.
     * On the sample data, none is listed.
     *
     * @param pageable the page to return, and its sort; must not be {@code null}.
     * @return a page of the addresses no customer, staff member or store refers to.
     */
    default Page<Address> listUnused(final Pageable pageable) {
        Objects.requireNonNull(pageable, "pageable is null");
        final Specification<Address> specification = (r, q, b) -> {
            final var customers = Objects.requireNonNull(q).subquery(Integer.class);
            final var c = customers.from(Customer.class);
            customers.select(b.literal(1)).where(b.equal(c.get(Customer_.address), r));
            final var staffs = q.subquery(Integer.class);
            final var s = staffs.from(Staff.class);
            staffs.select(b.literal(1)).where(b.equal(s.get(Staff_.address), r));
            final var stores = q.subquery(Integer.class);
            final var t = stores.from(Store.class);
            stores.select(b.literal(1)).where(b.equal(t.get(Store_.address), r));
            return b.and(b.not(b.exists(customers)), b.not(b.exists(staffs)), b.not(b.exists(stores)));
        };
        return findAll(specification, pageable);
    }

    /**
     * Selects the pairs of addresses which share a postal code ({@code SAKILA-ADDRESS-A-02}, this module's own extra,
     * which orders by {@code addressId}, then by {@code otherAddressId}).
     * <p>
     * A self-join of {@code Address}, on the postal code, which keeps each pair once, the lower id first, and leaves
     * out the empty postal codes; a {@code null} one equals nothing, and pairs with nothing. A row is a pair, of two
     * addresses, which a {@link Specification} of addresses cannot select; hence a {@link Query} and a projection. The
     * count query counts the same pairs.
     *
     * @param pageable the page to return, and its sort, by {@code addressId}, {@code address}, {@code otherAddressId},
     *                 {@code otherAddress} or {@code postalCode}; must not be {@code null}.
     * @return a page of the pairs of addresses which share a postal code.
     */
    @Query(value = """
            SELECT a1.addressId AS addressId, a1.address AS address,
                   a2.addressId AS otherAddressId, a2.address AS otherAddress,
                   a1.postalCode AS postalCode
            FROM Address a1
                     JOIN Address a2 ON a2.postalCode = a1.postalCode AND a2.addressId > a1.addressId
            WHERE a1.postalCode <> ''""",
           countQuery = """
                   SELECT COUNT(a2)
                   FROM Address a1
                            JOIN Address a2 ON a2.postalCode = a1.postalCode AND a2.addressId > a1.addressId
                   WHERE a1.postalCode <> ''""")
    Page<AddressPair> selectPairsSharingPostalCode(Pageable pageable);

    /**
     * Selects the three districts with the most addresses in each of India, China and the United States
     * ({@code SAKILA-ADDRESS-A-03}, native-only, which orders by {@code country}, then by the rank of the district in
     * the country: the most addresses first, then by {@code district}).
     * <p>
     * A top-N per group: {@code ROW_NUMBER()} over a partition by country numbers the districts, and the outer query
     * keeps the first three. JPQL has no window function, so this is a {@link NativeQuery} of the exercise's SQL, the
     * order and the countries with it.
     *
     * @return a list of the countries, each with its three districts of the most addresses, and their numbers of
     *         addresses.
     */
    @NativeQuery("""
            SELECT country, district, addresses
            FROM (SELECT co.country,
                         a.district,
                         COUNT(*)                                                                       AS addresses,
                         ROW_NUMBER() OVER (PARTITION BY co.country_id ORDER BY COUNT(*) DESC, a.district) AS district_rank
                  FROM address a
                           JOIN city ci ON ci.city_id = a.city_id
                           JOIN country co ON co.country_id = ci.country_id
                  WHERE co.country IN ('India', 'China', 'United States')
                  GROUP BY co.country_id, co.country, a.district) ranked
            WHERE district_rank <= 3
            ORDER BY country, district_rank""")
    List<CountryDistrictCount> selectTopThreeDistrictsOfIndiaChinaAndUnitedStates();
}
