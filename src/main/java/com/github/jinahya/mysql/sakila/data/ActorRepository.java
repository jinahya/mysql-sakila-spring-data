package com.github.jinahya.mysql.sakila.data;

import com.github.jinahya.mysql.sakila.persistence.Actor;
import com.github.jinahya.mysql.sakila.persistence.Actor_;
import com.github.jinahya.mysql.sakila.persistence.Film;
import com.github.jinahya.mysql.sakila.persistence.FilmActor;
import com.github.jinahya.mysql.sakila.persistence.FilmActor_;
import com.github.jinahya.mysql.sakila.persistence.Film_;
import jakarta.persistence.Tuple;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.domain.Specification;
import org.springframework.data.jpa.repository.Query;
import org.springframework.stereotype.Repository;

import java.util.List;
import java.util.Objects;
import java.util.stream.Stream;

/**
 * A repository for {@link Actor}, the {@code actor} table of the Sakila database.
 * <p>
 * The id is an {@link Integer} generated by the database ({@code GenerationType.IDENTITY}), so a newly constructed
 * actor is saved with no id, and the id is set on the saved instance. An actor has no business key:
 * {@link Actor#equals(Object)} compares ids, and only once they are assigned, so two unsaved actors are never equal.
 * Neither name is unique on its own, and the two together are not either; the sample data holds five actors named
 * {@code KILMER} and four named {@code PENELOPE}.
 * <p>
 * {@link _Repository} brings {@link org.springframework.data.jpa.repository.JpaSpecificationExecutor} for criteria
 * queries. Name the attributes through the generated static metamodel rather than by string, for example
 * {@code (root, query, builder) -> builder.equal(root.get(Actor_.lastName), lastName)}.
 * <p>
 * {@link Actor} declares named queries too ({@code Actor.selectOneByActorId},
 * {@code Actor.selectListOrderByActorIdAsc}, {@code Actor.selectListOrderByActorIdAscActorIdGt},
 * {@code Actor.selectListByLastNameOrderByFirstNameAsc} and {@code Actor.countAll}), but no method here runs them yet.
 * One that does is named after the query, and binds its parameters with {@code @Param}. The methods below derive their
 * queries from their names, or declare them with {@link Query}.
 * <p>
 * The methods after the first two answer the exercises of upstream's {@code EXERCISES.asciidoc} on the {@code actor}
 * table, one method per exercise, named in each method's javadoc by the exercise's id ({@code SAKILA-ACTOR-B-01},
 * ...), with its role: the book's pick, or this module's own extra. The exercises are context, not contract. A Basic
 * exercise is a derived query, with the order the exercise asks for in its name, and returns a {@link List} (the
 * book's pick) or a {@link Stream} (this module's own extra), with no {@link Pageable}. An Intermediate or Advanced
 * one takes a {@link Pageable}, the page and the sort, and returns a {@link Page}, so the order the exercise asks
 * for, and its {@code LIMIT}, are the caller's {@code PageRequest}; each method's javadoc says which sort that is. An
 * exercise that shows rows is a {@code default} method, {@code list...}, which builds a {@link Specification} with the
 * Criteria API and runs it through {@link org.springframework.data.jpa.repository.JpaSpecificationExecutor}. An
 * exercise that shows columns, grouped and counted, or taken from other entities, cannot be a {@code Specification},
 * which only filters; such a method, {@code select...}, declares its JPQL with {@link Query}, with a count query of
 * its own since Spring Data cannot derive one from a grouped select. Such a query selects entities, not their
 * columns: an actor is selected whole ({@code SELECT a AS actor}), and grouped by itself ({@code GROUP BY a}) where
 * the query groups; what is computed, a count, a sum, an expression, is a column of its own beside it. A result that
 * is a single entity is that entity; any other comes back as a {@link jakarta.persistence.Tuple}, each element read
 * by its alias, with its type ({@code tuple.get("actor", Actor.class)}, {@code tuple.get("films", Long.class)}).
 * The {@code Pageable} sorts a computed column by its alias ({@code Sort.by(DESC, "films")}), and an attribute of a
 * selected entity by its path from the query's identification variable ({@code Sort.by("a.actorId")}); each method's
 * javadoc names its aliases and identification variables. A query which groups by a value, not by an entity (the
 * last names shared by more than a number of actors), still selects that value.
 *
 * @see Actor
 * @see Actor_
 */
@Repository
public interface ActorRepository
        extends _Repository<Actor, Integer> {

    /**
     * Finds the actors whose value of {@link Actor_#FIRST_NAME} attribute is equal to the specified value.
     * <p>
     * The query is derived from the method name. The comparison is the database's, which on the Sakila database is
     * case-insensitive, by the collation of the column, so {@code "penelope"} finds {@code PENELOPE} there.
     * <p>
     * The {@code pageable} limits and sorts the result. A {@link List} carries no count of all matches, so, unlike for
     * a {@link org.springframework.data.domain.Page}, no second {@code COUNT} query runs. The query has no order of
     * its own, so give {@code pageable} a sort, such as by {@link Actor_#ACTOR_ID}, or the pages are not stable.
     *
     * @param firstName the value of the {@link Actor_#FIRST_NAME} attribute to match; must not be {@code null}.
     * @param pageable  the page to return, and its sort; {@link Pageable#unpaged()} for all matches in one page. Must
     *                  not be {@code null}.
     * @return a list of the actors whose first name is {@code firstName}; empty if there is none.
     * @see #findAllByLastName(String, Pageable)
     */
    List<Actor> findAllByFirstName(String firstName, Pageable pageable);

    /**
     * Finds the actors whose value of {@link Actor_#LAST_NAME} attribute is equal to the specified value, as a stream.
     * <p>
     * The query is derived from the method name, and the comparison is the database's, as in
     * {@link #findAllByFirstName(String, Pageable)}. The {@code pageable} limits and sorts what the stream yields, as
     * it does the list there.
     * <p>
     * A {@link Stream} reads the rows as they are consumed, over a result set that stays open until the stream is
     * closed, so close it, in a try-with-resources. It also has to be consumed inside a transaction the caller opened:
     * the transaction the repository opens for itself ends when this method returns, which would close the result set
     * under the stream, so Spring Data refuses a call that no transaction surrounds, with an
     * {@link org.springframework.dao.InvalidDataAccessApiUsageException}, before any query runs.
     *
     * @param lastName the value of the {@link Actor_#LAST_NAME} attribute to match; must not be {@code null}.
     * @param pageable the page to return, and its sort; {@link Pageable#unpaged()} for all matches in one page. Must
     *                 not be {@code null}.
     * @return a stream of the actors whose last name is {@code lastName}, to be closed by the caller; empty if there is
     *         none.
     * @see #findAllByFirstName(String, Pageable)
     */
    Stream<Actor> findAllByLastName(String lastName, Pageable pageable);

    // ----------------------------------------------------------------------------------------------------- exercises




    /**
     * Finds the actors whose value of {@link Actor_#LAST_NAME} attribute is equal to the specified value, by
     * {@link Actor_#ACTOR_ID} ({@code SAKILA-ACTOR-B-01}, the book's pick, which orders by {@link Actor_#ACTOR_ID}).
     * <p>
     * The query, and its order, are derived from the method name; the comparison is the database's, as in
     * {@link #findAllByFirstName(String, Pageable)}. The match is the whole list, which the exercise bounds by its
     * filter, so there is no {@link Pageable}.
     *
     * @param lastName the value of the {@link Actor_#LAST_NAME} attribute to match; must not be {@code null}.
     * @return a list of the actors whose last name is {@code lastName}, by id; empty if there is none.
     */
    List<Actor> findAllByLastNameOrderByActorIdAsc(String lastName);

    /**
     * Finds the actors whose value of {@link Actor_#FIRST_NAME} attribute starts with the specified prefix, as a
     * stream, by {@link Actor_#FIRST_NAME} and then by {@link Actor_#ACTOR_ID} ({@code SAKILA-ACTOR-B-02}, this
     * module's own extra, which orders by {@link Actor_#FIRST_NAME}, then by {@link Actor_#ACTOR_ID} so that the order
     * is the same every time).
     * <p>
     * The query, and its order, are derived from the method name. {@code StartingWith} is a {@code LIKE} with the
     * trailing {@code %} added by Spring Data, which escapes any wildcard in the prefix, so the caller passes the
     * prefix alone. The stream is to be consumed inside a transaction the caller opened, and closed, as the one of
     * {@link #findAllByLastName(String, Pageable)}.
     *
     * @param prefix the prefix of the {@link Actor_#FIRST_NAME} attribute to match; must not be {@code null}.
     * @return a stream of the actors whose first name starts with {@code prefix}, by first name and then by id, to be
     *         closed by the caller; empty if there is none.
     */
    Stream<Actor> findAllByFirstNameStartingWithOrderByFirstNameAscActorIdAsc(String prefix);

    /**
     * Selects the last names shared by more than the specified number of actors, with their counts
     * ({@code SAKILA-ACTOR-I-01}, this module's own extra, which orders by {@code actors} descending, then by {@code lastName}).
     * <p>
     * The actors are grouped by last name and counted; the filter is on the groups, so it is a {@code HAVING}, not a
     * {@code WHERE}, and a {@link Specification}, which filters rows, cannot do it. The count query counts the names
     * that pass the same {@code HAVING}, through a subquery.
     *
     * @param actors   the number of actors a last name has to be shared by more than.
     * @param pageable the page to return, and its sort, by {@code lastName} or {@code actors}; must not be
     *                 {@code null}.
     * @return a page of the last names shared by more than {@code actors} actors, with their counts, each a tuple of
     *         {@code lastName} ({@link String}) and {@code actors} ({@link Long}).
     */
    @Query(value = """
            SELECT a.lastName AS lastName, COUNT(a) AS actors
            FROM Actor a
            GROUP BY a.lastName
            HAVING COUNT(a) > :actors""",
           countQuery = """
                   SELECT COUNT(DISTINCT a.lastName)
                   FROM Actor a
                   WHERE a.lastName IN (SELECT a2.lastName
                                        FROM Actor a2
                                        GROUP BY a2.lastName
                                        HAVING COUNT(a2) > :actors)""")
    Page<Tuple> selectLastNamesSharedByMoreThan(long actors, Pageable pageable);

    /**
     * Selects the actors who appear in at least one film, with how many ({@code SAKILA-ACTOR-I-02}, the book's pick, which takes the
     * first five by {@code films} descending, then by {@code a.actorId}, so that the five are always the same five).
     * <p>
     * The films are counted through the actor's {@link Actor_#FILM_ACTORS} links, by an inner join, so an actor with
     * no film is not in the page; the actors are grouped by the actor itself, which selects the actor whole. The count
     * query counts the actors that have a film.
     *
     * @param pageable the page to return, and its sort, by {@code films}, or by an attribute of the actor through
     *                 {@code a} ({@code a.actorId}, {@code a.lastName}, ...); must not be {@code null}.
     * @return a page of the actors who appear in a film, with their numbers of films, each a tuple of {@code actor}
     *         ({@link Actor}) and {@code films} ({@link Long}).
     */
    @Query(value = """
            SELECT a AS actor, COUNT(fa) AS films
            FROM Actor a
            JOIN a.filmActors fa
            GROUP BY a""",
           countQuery = """
                   SELECT COUNT(a)
                   FROM Actor a
                   WHERE a.filmActors IS NOT EMPTY""")
    Page<Tuple> selectFilmCounts(Pageable pageable);

    /**
     * Lists the actors who appear in a film of every rating ({@code SAKILA-ACTOR-A-01}, the book's pick, which takes the first five
     * by {@link Actor_#ACTOR_ID}).
     * <p>
     * A relational division, as a {@link Specification} of two subqueries: an actor qualifies when the distinct
     * ratings of their films are as many as the distinct ratings of all films. The second count is a subquery too, so
     * the ratings are not hard-coded; a film with no rating counts for neither side.
     *
     * @param pageable the page to return, and its sort; must not be {@code null}.
     * @return a page of the actors who appear in a film of every rating.
     */
    default Page<Actor> listInEveryRating(final Pageable pageable) {
        Objects.requireNonNull(pageable, "pageable is null");
        final Specification<Actor> specification = (r, q, b) -> {
            final var ratingsOfTheActor = Objects.requireNonNull(q).subquery(Long.class);
            final var fa = ratingsOfTheActor.from(FilmActor.class);
            ratingsOfTheActor.select(b.countDistinct(fa.get(FilmActor_.film).get(Film_.rating)))
                    .where(b.equal(fa.get(FilmActor_.actor), r));
            final var ratingsOfAllFilms = q.subquery(Long.class);
            final var f = ratingsOfAllFilms.from(Film.class);
            ratingsOfAllFilms.select(b.countDistinct(f.get(Film_.rating)));
            return b.equal(ratingsOfTheActor, ratingsOfAllFilms);
        };
        return findAll(specification, pageable);
    }

    /**
     * Selects, for each actor whose id is in the specified range, the actor's films of the longest length
     * ({@code SAKILA-ACTOR-A-03}, this module's own extra, which takes the actors {@code 1} to {@code 5}, and orders by
     * {@code a.actorId}, then by {@code f.title}).
     * <p>
     * A correlated subquery finds the longest length of the films of the actor of each row, and the outer query keeps
     * the films of that length; two films that tie are two rows. The select takes two entities, the actor and the
     * film, which a {@link Specification} of actors cannot select; hence a {@link Query} and a tuple. The count query
     * counts the same rows.
     *
     * @param minActorId the lowest {@link Actor_#ACTOR_ID} of the range, inclusive.
     * @param maxActorId the highest {@link Actor_#ACTOR_ID} of the range, inclusive.
     * @param pageable   the page to return, and its sort, by an attribute of the actor through {@code a}
     *                   ({@code a.actorId}, ...) or of the film through {@code f} ({@code f.title},
     *                   {@code f.length}, ...); must not be {@code null}.
     * @return a page of the actors whose ids are in the range, each with a longest film of theirs, as a tuple of
     *         {@code actor} ({@link Actor}) and {@code film} ({@link Film}).
     */
    @Query(value = """
            SELECT a AS actor, f AS film
            FROM Actor a
                     JOIN a.filmActors fa
                     JOIN fa.film f
            WHERE a.actorId BETWEEN :minActorId AND :maxActorId
              AND f.length = (SELECT MAX(f2.length)
                              FROM FilmActor fa2
                                       JOIN fa2.film f2
                              WHERE fa2.actor = a)""",
           countQuery = """
                   SELECT COUNT(fa)
                   FROM Actor a
                            JOIN a.filmActors fa
                            JOIN fa.film f
                   WHERE a.actorId BETWEEN :minActorId AND :maxActorId
                     AND f.length = (SELECT MAX(f2.length)
                                     FROM FilmActor fa2
                                              JOIN fa2.film f2
                                     WHERE fa2.actor = a)""")
    Page<Tuple> selectLongestFilmsOfActorIdsBetween(int minActorId, int maxActorId, Pageable pageable);
}
