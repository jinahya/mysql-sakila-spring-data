package com.github.jinahya.mysql.sakila.data;

import com.github.jinahya.mysql.sakila.persistence.Film;
import com.github.jinahya.mysql.sakila.persistence.Film_;
import com.github.jinahya.mysql.sakila.persistence.Language;
import com.github.jinahya.mysql.sakila.persistence.Language_;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.domain.Specification;
import org.springframework.data.jpa.repository.Query;
import org.springframework.stereotype.Repository;

import java.util.Collection;
import java.util.List;
import java.util.Objects;
import java.util.stream.Stream;

/**
 * A repository for {@link Language}, the {@code language} table of the Sakila database.
 * <p>
 * The id is an {@link Integer} generated by the database ({@code GenerationType.IDENTITY}), so a newly constructed
 * language is saved with no id, and the id is set on the saved instance. A language has a
 * {@link Language_#NAME}, of at most twenty characters, and nothing else of its own; a film refers to it twice, as
 * its {@link Film_#LANGUAGE}, {@code NOT NULL}, and as its {@link Film_#ORIGINAL_LANGUAGE}, which may be
 * {@code null}. The films whose language it is are mapped as the language's {@link Language_#FILMS}, whose getter is
 * not public upstream; a query reaches them through JPQL or a {@link Specification}.
 * <p>
 * {@link _Repository} brings {@link org.springframework.data.jpa.repository.JpaSpecificationExecutor} for criteria
 * queries. Name the attributes through the generated static metamodel rather than by string, for example
 * {@code (root, query, builder) -> builder.equal(root.get(Language_.name), name)}.
 * <p>
 * The methods below answer the exercises of upstream's {@code EXERCISES.asciidoc} on the {@code language} table, one
 * method per exercise, named in each method's javadoc by the exercise's id ({@code SAKILA-LANGUAGE-B-01}, ...) and
 * its role: the book's pick or this module's own extra. The exercises are context, not contract. A Basic one is
 * plain: the book's pick returns a {@link List}, this module's own extra a {@link Stream}, and the order the exercise
 * asks for is in the query, here in the method's name. An Intermediate one takes a {@link Pageable}, the page and the
 * sort, and returns a {@link Page}, so the order the exercise asks for is the caller's {@code PageRequest}; each
 * method's javadoc says which sort that is. An exercise that shows rows of languages is a {@code default} method,
 * {@code list...}, which builds a {@link Specification} with the Criteria API and runs it through
 * {@link org.springframework.data.jpa.repository.JpaSpecificationExecutor}. An exercise that shows columns, grouped
 * and counted, cannot be a {@link Specification}, which only filters; such a method, {@code select...}, declares its
 * JPQL with {@link Query}, with a count query of its own since Spring Data cannot derive one from a grouped select,
 * and returns a projection, one of the interfaces declared here, which Spring Data backs with the selected columns,
 * each aliased with the name of the getter it feeds. Those aliases are what the {@code Pageable} sorts by; an
 * interface rather than a record, because Spring Data rewrites a record projection into a constructor expression,
 * which drops the aliases, and the sort with them.
 *
 * @see Language
 * @see Language_
 */
@Repository
public interface LanguageRepository
        extends _Repository<Language, Integer> {

    // ----------------------------------------------------------------------------------------------------- exercises

    /**
     * A language, by id and name, and how many films are in it: a projection of {@link #selectFilmCounts(Pageable)},
     * sortable by {@code languageId}, {@code name} and {@code films}.
     */
    interface LanguageFilmCount {

        /**
         * Returns the id of the language.
         *
         * @return the id of the language.
         */
        Integer getLanguageId();

        /**
         * Returns the name of the language.
         *
         * @return the name of the language.
         */
        String getName();

        /**
         * Returns the number of films whose language it is.
         *
         * @return the number of films; {@code 0} for a language no film is in.
         */
        long getFilms();
    }

    /**
     * Finds every language ({@code SAKILA-LANGUAGE-B-01}, the book's pick, which orders by
     * {@link Language_#LANGUAGE_ID}).
     * <p>
     * The query is derived from the method name: no criteria, and the exercise's order, which {@code findAll()}
     * alone would not guarantee.
     *
     * @return a list of every language, by id.
     */
    List<Language> findAllByOrderByLanguageIdAsc();

    /**
     * Finds the languages whose value of {@link Language_#NAME} attribute is one of the specified names, as a stream
     * ({@code SAKILA-LANGUAGE-B-03}, this module's own extra, which asks for English, French, German and Spanish, and
     * orders by {@link Language_#NAME}).
     * <p>
     * The query is derived from the method name, an {@code IN} on the name, in the exercise's order; a name no
     * language has is simply not matched. The comparison is the database's, which on the Sakila database is
     * case-insensitive, by the collation of the column.
     * <p>
     * A {@link Stream} reads the rows as they are consumed, over a result set that stays open until the stream is
     * closed, so close it, in a try-with-resources. It also has to be consumed inside a transaction the caller opened:
     * the transaction the repository opens for itself ends when this method returns, which would close the result set
     * under the stream, so Spring Data refuses a call that no transaction surrounds, with an
     * {@link org.springframework.dao.InvalidDataAccessApiUsageException}, before any query runs.
     *
     * @param names the names to match; must not be {@code null}.
     * @return a stream of the languages whose name is one of {@code names}, by name, to be closed by the caller; empty
     *         if there is none.
     */
    Stream<Language> findAllByNameInOrderByNameAsc(Collection<String> names);

    /**
     * Selects every language, with how many films are in it ({@code SAKILA-LANGUAGE-I-01}, the book's pick, which
     * orders by {@code languageId}).
     * <p>
     * The language's {@link Language_#FILMS} are joined with a {@code LEFT JOIN}, so a language no film is in is
     * selected too, with a count of zero: {@code COUNT(f)} counts the films, not the rows, and the one row such a
     * language joins has no film. Every language is a group, so the count query counts the languages.
     *
     * @param pageable the page to return, and its sort, by {@code languageId}, {@code name} or {@code films}; must
     *                 not be {@code null}.
     * @return a page of the languages, with their numbers of films.
     */
    @Query(value = """
            SELECT l.languageId AS languageId, l.name AS name, COUNT(f) AS films
            FROM Language l
            LEFT JOIN l.films f
            GROUP BY l.languageId, l.name""",
           countQuery = """
                   SELECT COUNT(l)
                   FROM Language l""")
    Page<LanguageFilmCount> selectFilmCounts(Pageable pageable);

    /**
     * Lists the languages no film uses, either as its language or as its original language
     * ({@code SAKILA-LANGUAGE-I-02}, this module's own extra, which orders by {@link Language_#LANGUAGE_ID}).
     * <p>
     * A {@link Specification} of one {@code NOT EXISTS}, on a subquery of the films whose
     * {@link Film_#LANGUAGE} or {@link Film_#ORIGINAL_LANGUAGE} is the language; a film with no original language
     * matches by its language alone.
     *
     * @param pageable the page to return, and its sort; must not be {@code null}.
     * @return a page of the languages no film uses.
     */
    default Page<Language> listUnused(final Pageable pageable) {
        Objects.requireNonNull(pageable, "pageable is null");
        final Specification<Language> specification = (r, q, b) -> {
            final var using = Objects.requireNonNull(q).subquery(Film.class);
            final var f = using.from(Film.class);
            using.select(f)
                    .where(b.or(b.equal(f.get(Film_.language), r),
                                b.equal(f.get(Film_.originalLanguage), r)));
            return b.not(b.exists(using));
        };
        return findAll(specification, pageable);
    }
}
