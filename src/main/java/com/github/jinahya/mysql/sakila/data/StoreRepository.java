package com.github.jinahya.mysql.sakila.data;

import com.github.jinahya.mysql.sakila.persistence.Address_;
import com.github.jinahya.mysql.sakila.persistence.Store;
import com.github.jinahya.mysql.sakila.persistence.Store_;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.domain.Specification;
import org.springframework.data.jpa.repository.Query;
import org.springframework.stereotype.Repository;

import java.util.Objects;

/**
 * A repository for {@link Store}, the {@code store} table of the Sakila database.
 * <p>
 * The id is an {@link Integer} generated by the database ({@code GenerationType.IDENTITY}), so a newly constructed
 * store is saved with no id, and the id is set on the saved instance. Unlike most entities of the schema, a store has
 * a business key: {@link Store#equals(Object)} compares the ids of the managers ({@link Store_#MANAGER_STAFF}), a
 * one-to-one which is unique on the table. A store names its manager, a staff member, and has an address
 * ({@link Store_#ADDRESS}), both {@code NOT NULL}; the manager, in turn, works at a store, so the two tables refer to
 * each other. The customers and the copies of a store are mapped as collections, but their getters are not public
 * upstream, so a caller that needs them reads them through {@link CustomerRepository} or
 * {@link InventoryRepository}, with a {@link Specification}.
 * <p>
 * {@link _Repository} brings {@link org.springframework.data.jpa.repository.JpaSpecificationExecutor} for criteria
 * queries. Name the attributes through the generated static metamodel rather than by string, for example
 * {@code (root, query, builder) -> builder.equal(root.get(Store_.managerStaff), staff)}.
 * <p>
 * The methods below answer the exercises of upstream's {@code EXERCISES_COORDINATES.asciidoc} on the {@code store} table, one
 * method per exercise, named in each method's javadoc by the exercise's id ({@code SAKILA-STORE-I-01}, ...), one or
 * two of each level. The exercises are context, not contract: each method takes a {@link Pageable}, the page and the
 * sort, and returns a {@link Page}, so the order the exercise asks for, and its {@code LIMIT}, are the caller's
 * {@code PageRequest}; each method's javadoc says which sort that is. An exercise that shows rows is a {@code default}
 * method, {@code list...}, which builds a {@link Specification} with the Criteria API and runs it through
 * {@link org.springframework.data.jpa.repository.JpaSpecificationExecutor}. An exercise that shows columns, counted
 * or grouped, cannot be a {@code Specification}, which only filters; such a method, {@code select...}, declares its
 * JPQL with {@link Query}, with a count query of its own since Spring Data cannot derive one from a grouped select,
 * and returns a projection, one of the interfaces declared here, which Spring Data backs with the selected columns,
 * each aliased with the name of the getter it feeds. Those aliases are what the {@code Pageable} sorts by; an
 * interface rather than a record, because Spring Data rewrites a record projection into a constructor expression,
 * which drops the aliases, and the sort with them.
 *
 * @see Store
 * @see Store_
 */
@Repository
public interface StoreRepository
        extends _Repository<Store, Integer> {

    // ----------------------------------------------------------------------------------------------------- exercises

    /**
     * A store, by id, and how many customers, copies and staff members it has: a projection of
     * {@link #selectCounts(Pageable)}, sortable by {@code storeId}, {@code customers}, {@code copies} and
     * {@code staff}.
     */
    interface StoreCounts {

        /**
         * Returns the id of the store.
         *
         * @return the id of the store.
         */
        Integer getStoreId();

        /**
         * Returns the number of customers of the store.
         *
         * @return the number of customers.
         */
        long getCustomers();

        /**
         * Returns the number of copies in the inventory of the store.
         *
         * @return the number of copies.
         */
        long getCopies();

        /**
         * Returns the number of staff members who work at the store.
         *
         * @return the number of staff members.
         */
        long getStaff();
    }

    /**
     * A store, by id, and how many films it has a copy of, and how many of those no other store has a copy of: a
     * projection of {@link #selectFilmCounts(Pageable)}, sortable by {@code storeId}, {@code films} and
     * {@code filmsOnlyHere}.
     */
    interface StoreFilmCounts {

        /**
         * Returns the id of the store.
         *
         * @return the id of the store.
         */
        Integer getStoreId();

        /**
         * Returns the number of distinct films the store has at least one copy of.
         *
         * @return the number of films.
         */
        long getFilms();

        /**
         * Returns the number of those films no other store has a copy of.
         *
         * @return the number of films only this store has.
         */
        long getFilmsOnlyHere();
    }

    /**
     * Lists every store, with its manager and the city of its address ({@code SAKILA-STORE-I-01}, which orders by
     * {@link Store_#STORE_ID}).
     * <p>
     * A {@link Specification} with no predicate, which fetches the {@link Store_#MANAGER_STAFF}, and the
     * {@link Store_#ADDRESS} with its {@link Address_#CITY}, two joins away, along with each store, so that all three,
     * lazy otherwise, are loaded by the same select and can be read once the page is detached. The fetches are skipped
     * for the count query Spring Data runs for the page, whose result type is {@link Long}: a count fetches nothing.
     *
     * @param pageable the page to return, and its sort; must not be {@code null}.
     * @return a page of the stores, each with its manager, its address and the address's city loaded.
     */
    default Page<Store> listWithManagerAndCity(final Pageable pageable) {
        Objects.requireNonNull(pageable, "pageable is null");
        final Specification<Store> specification = (r, q, b) -> {
            final var resultType = Objects.requireNonNull(q).getResultType();
            if (resultType != Long.class && resultType != long.class) {
                r.fetch(Store_.managerStaff);
                r.fetch(Store_.address).fetch(Address_.city);
            }
            return b.conjunction();
        };
        return findAll(specification, pageable);
    }

    /**
     * Selects every store, by id, with the numbers of its customers, its copies and its staff members
     * ({@code SAKILA-STORE-I-02}, which orders by {@code storeId}).
     * <p>
     * The three counts come from three tables, and joining all three at once would multiply the rows, so each is a
     * correlated scalar subquery in the select, on the store of the row. Nothing is grouped, but the columns are
     * counts, which a {@link Specification} cannot select; the count query counts the stores.
     *
     * @param pageable the page to return, and its sort, by {@code storeId}, {@code customers}, {@code copies} or
     *                 {@code staff}; must not be {@code null}.
     * @return a page of the stores, with their three counts.
     */
    @Query(value = """
            SELECT st.storeId AS storeId,
                   (SELECT COUNT(c) FROM Customer c WHERE c.store = st) AS customers,
                   (SELECT COUNT(i) FROM Inventory i WHERE i.store = st) AS copies,
                   (SELECT COUNT(s) FROM Staff s WHERE s.store = st) AS staff
            FROM Store st""",
           countQuery = """
                   SELECT COUNT(st)
                   FROM Store st""")
    Page<StoreCounts> selectCounts(Pageable pageable);

    /**
     * Selects the stores that have a copy of a film, by id, with how many distinct films they have a copy of, and how
     * many of those no other store has a copy of ({@code SAKILA-STORE-A-01}, which orders by {@code storeId}).
     * <p>
     * The copies are reached through the store's {@link Store_#INVENTORIES}, by an inner join, and grouped by store;
     * the first count is of the distinct film ids. The second is of the distinct film ids that a {@code CASE} keeps,
     * which it does when no copy of the film exists in a store other than the one of the group, a correlated
     * {@code NOT EXISTS}; a film another store has falls out of the {@code CASE} as {@code null}, which the count
     * ignores. The count query counts the stores that have a copy.
     *
     * @param pageable the page to return, and its sort, by {@code storeId}, {@code films} or {@code filmsOnlyHere};
     *                 must not be {@code null}.
     * @return a page of the stores that have a copy, with their two counts.
     */
    @Query(value = """
            SELECT st.storeId AS storeId,
                   COUNT(DISTINCT i.filmId) AS films,
                   COUNT(DISTINCT CASE
                                      WHEN NOT EXISTS (SELECT o
                                                       FROM Inventory o
                                                       WHERE o.filmId = i.filmId AND o.storeId <> st.storeId)
                                          THEN i.filmId
                                  END) AS filmsOnlyHere
            FROM Store st
            JOIN st.inventories i
            GROUP BY st.storeId""",
           countQuery = """
                   SELECT COUNT(st)
                   FROM Store st
                   WHERE st.inventories IS NOT EMPTY""")
    Page<StoreFilmCounts> selectFilmCounts(Pageable pageable);
}
