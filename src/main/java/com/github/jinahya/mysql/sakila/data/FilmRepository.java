package com.github.jinahya.mysql.sakila.data;

import com.github.jinahya.mysql.sakila.persistence.Film;
import com.github.jinahya.mysql.sakila.persistence.Film_;
import jakarta.persistence.Tuple;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.domain.Specification;
import org.springframework.data.jpa.repository.Query;
import org.springframework.stereotype.Repository;

import java.util.List;
import java.util.Objects;
import java.util.stream.Stream;

/**
 * A repository for {@link Film}, the {@code film} table of the Sakila database.
 * <p>
 * The id is an {@link Integer} generated by the database ({@code GenerationType.IDENTITY}), so a newly constructed
 * film is saved with no id, and the id is set on the saved instance. A film has no business key:
 * {@link Film#equals(Object)} compares ids, and only once they are assigned. The {@code rating} is an {@code ENUM}
 * column, mapped to {@link Film.Rating} through a converter, so a query compares and sorts it as the database does:
 * on the Sakila database in the order of the {@code ENUM}'s values, which is the order of the enum's constants. The
 * {@code special_features} is a {@code SET} column, mapped as one {@link String} of comma-separated values.
 * <p>
 * {@link _Repository} brings {@link org.springframework.data.jpa.repository.JpaSpecificationExecutor} for criteria
 * queries. Name the attributes through the generated static metamodel rather than by string, for example
 * {@code (root, query, builder) -> builder.greaterThan(root.get(Film_.length), length)}.
 * <p>
 * {@link Film} declares named queries too ({@code Film.selectOneByFilmId}, {@code Film.selectListOrderByFilmIdAsc},
 * {@code Film.selectListByTitleOrderByFilmIdAsc}, {@code Film.selectListByRatingOrderByFilmIdAsc}, ...), but no
 * method here runs them yet. One that does is named after the query, and binds its parameters with {@code @Param}.
 * <p>
 * The methods below answer the exercises of upstream's {@code EXERCISES.asciidoc} on the {@code film} table, one
 * method per exercise, in the order of the exercises' ids, each named in its javadoc by the id
 * ({@code SAKILA_FILM_B_01}, ...) and by its role: the book's pick, this module's own extra, or not a pick, kept from
 * before the picks. The exercises are context, not contract. A Basic one is plain: no {@link Pageable}, the order the
 * exercise asks for written in the query, a {@link List} for the book's pick and a {@link Stream} for this module's
 * own extra. An Intermediate or Advanced one takes a {@link Pageable}, the page and the sort, and returns a
 * {@link Page}, so the order the exercise asks for, and its {@code LIMIT}, are the caller's {@code PageRequest}; each
 * method's javadoc says which sort that is. An exercise that counts the rows of a filter is answered by the page of
 * those rows, whose {@link Page#getTotalElements()} is the count. An exercise that shows rows is a {@code default}
 * method, {@code list...}, which builds a {@link Specification} with the Criteria API and runs it through
 * {@link org.springframework.data.jpa.repository.JpaSpecificationExecutor}. An exercise that shows columns, grouped
 * and counted, cannot be a {@link Specification}, which only filters; such a method, {@code select...}, declares its
 * JPQL with {@link Query}, with a count query of its own since Spring Data cannot derive one from a grouped select.
 * Such a query selects entities, not their columns: a film is selected whole ({@code SELECT f AS film}), and grouped
 * by itself ({@code GROUP BY f}) where the query groups; what is computed, a count, an average, is a column of its
 * own beside it. A result that is a single entity is that entity; any other comes back as a
 * {@link jakarta.persistence.Tuple}, each element read by its alias, with its type
 * ({@code tuple.get("film", Film.class)}, {@code tuple.get("rentals", Long.class)}). The {@code Pageable} sorts a
 * computed column by its alias ({@code Sort.by(DESC, "rentals")}), and an attribute of a selected entity by its path
 * from the query's identification variable ({@code Sort.by("f.filmId")}); each method's javadoc names its aliases
 * and identification variables. A query which groups by a value, not by an entity (the ratings), still selects that
 * value.
 *
 * @see Film
 * @see Film_
 */
@Repository
public interface FilmRepository
        extends _Repository<Film, Integer> {

    // ----------------------------------------------------------------------------------------------------- exercises

    /**
     * Selects the ratings, with how many films each has ({@code SAKILA_FILM_B_01}, the book's pick, which orders by
     * {@code rating}).
     * <p>
     * The films are grouped by rating and counted, so it is a {@link Query}, not a {@link Specification}, and the
     * order is the query's own. A film with no rating is left out. The rating is an {@code ENUM} column on the Sakila
     * database, so the order there is that of the {@code ENUM}'s values, which is the order of {@link Film.Rating}'s
     * constants, not the alphabetical one.
     *
     * @return a list of the ratings, with their numbers of films, by rating, each a tuple of {@code rating}
     *         ({@link Film.Rating}) and {@code films} ({@link Long}).
     */
    @Query("""
            SELECT f.rating AS rating, COUNT(f) AS films
            FROM Film f
            WHERE f.rating IS NOT NULL
            GROUP BY f.rating
            ORDER BY f.rating""")
    List<Tuple> selectRatingCounts();

    /**
     * Lists the films whose value of {@link Film_#LENGTH} attribute is greater than the specified value
     * ({@code SAKILA_FILM_B_02}, not a pick, which takes the first five by {@link Film_#LENGTH} descending, then by
     * {@link Film_#TITLE}; the exercise asks for more than three hours, {@code 180}).
     * <p>
     * A {@link Specification} of one comparison; no join. A film with no length is not longer than anything, so it
     * is never listed.
     *
     * @param length   the length, in minutes, the films have to be longer than.
     * @param pageable the page to return, and its sort; must not be {@code null}.
     * @return a page of the films longer than {@code length} minutes.
     */
    default Page<Film> listLongerThan(final int length, final Pageable pageable) {
        Objects.requireNonNull(pageable, "pageable is null");
        final Specification<Film> specification = (r, q, b) -> b.greaterThan(r.get(Film_.length), length);
        return findAll(specification, pageable);
    }

    /**
     * Selects the ratings, with the average rental rate of the films of each, as a stream ({@code SAKILA_FILM_B_03},
     * this module's own extra, which orders by {@code rating}).
     * <p>
     * The films are grouped by rating, and the average of their {@link Film_#RENTAL_RATE} is rounded to two decimal
     * places in the query, as the exercise does. A film with no rating is left out, and the order is that of
     * {@link #selectRatingCounts()}.
     * <p>
     * A {@link Stream} reads the rows as they are consumed, over a result set that stays open until the stream is
     * closed, so close it, in a try-with-resources. It also has to be consumed inside a transaction the caller opened:
     * Spring Data refuses a call that no transaction surrounds, with an
     * {@link org.springframework.dao.InvalidDataAccessApiUsageException}, before any query runs.
     *
     * @return a stream of the ratings, with the average rental rates of their films, by rating, each a tuple of
     *         {@code rating} ({@link Film.Rating}) and {@code averageRentalRate} ({@link Double}), to be closed by the
     *         caller.
     */
    @Query("""
            SELECT f.rating AS rating, ROUND(AVG(f.rentalRate), 2) AS averageRentalRate
            FROM Film f
            WHERE f.rating IS NOT NULL
            GROUP BY f.rating
            ORDER BY f.rating""")
    Stream<Tuple> selectAverageRentalRates();

    /**
     * Lists the films which have no copy in the inventory ({@code SAKILA_FILM_I_01}, this module's own extra, which
     * asks how many; that is the page's {@link Page#getTotalElements()}, whatever its size, and the exercise names no
     * order).
     * <p>
     * A {@link Specification} of one {@code IS EMPTY} on the film's {@link Film_#INVENTORIES}, which the provider
     * renders as a {@code NOT EXISTS} on the {@code inventory} table; the count query Spring Data derives from it
     * counts the same films.
     *
     * @param pageable the page to return, and its sort; must not be {@code null}.
     * @return a page of the films with no copy.
     */
    default Page<Film> listWithoutInventory(final Pageable pageable) {
        Objects.requireNonNull(pageable, "pageable is null");
        final Specification<Film> specification = (r, q, b) -> b.isEmpty(r.get(Film_.inventories));
        return findAll(specification, pageable);
    }

    /**
     * Selects the films which were rented at least once, with how many times ({@code SAKILA_FILM_I_02}, the book's
     * pick, which takes the first five by {@code rentals} descending, then by {@code f.filmId}, so that the five
     * are always the same five).
     * <p>
     * A rental refers to a copy, and a copy to a film, so the rentals are counted through two inner joins, from the
     * film's {@link Film_#INVENTORIES} to each copy's rentals; a film never rented is not in the page. The films are
     * grouped by the film itself, which selects the film whole. The count query counts the films that have a rental,
     * through an {@code EXISTS}.
     *
     * @param pageable the page to return, and its sort, by {@code rentals}, or by an attribute of the film through
     *                 {@code f} ({@code f.filmId}, {@code f.title}, ...); must not be {@code null}.
     * @return a page of the films rented at least once, with their numbers of rentals, each a tuple of {@code film}
     *         ({@link Film}) and {@code rentals} ({@link Long}).
     */
    @Query(value = """
            SELECT f AS film, COUNT(r) AS rentals
            FROM Film f
            JOIN f.inventories i
            JOIN i.rentals r
            GROUP BY f""",
           countQuery = """
                   SELECT COUNT(f)
                   FROM Film f
                   WHERE EXISTS (SELECT r.rentalId
                                 FROM Rental r
                                 WHERE r.inventory.film = f)""")
    Page<Tuple> selectRentalCounts(Pageable pageable);

    /**
     * Selects the ratings, with how many of their films are longer than the average film of the rating
     * ({@code SAKILA_FILM_A_01}, the book's pick, which orders by {@code rating}).
     * <p>
     * A correlated subquery averages the {@link Film_#LENGTH} of the films of the outer film's rating; the films
     * longer than it are grouped by rating and counted. The count query counts the distinct ratings that keep a film
     * through the same filter. As in {@link #selectRatingCounts()}, a sort by {@code rating} on the Sakila database is
     * in the order of the {@code ENUM}'s values.
     *
     * @param pageable the page to return, and its sort, by {@code rating} or {@code films}; must not be {@code null}.
     * @return a page of the ratings, with their numbers of films longer than the rating's average, each a tuple of
     *         {@code rating} ({@link Film.Rating}) and {@code films} ({@link Long}).
     */
    @Query(value = """
            SELECT f1.rating AS rating, COUNT(f1) AS films
            FROM Film f1
            WHERE f1.length > (SELECT AVG(f2.length) FROM Film f2 WHERE f2.rating = f1.rating)
            GROUP BY f1.rating""",
           countQuery = """
                   SELECT COUNT(DISTINCT f1.rating)
                   FROM Film f1
                   WHERE f1.length > (SELECT AVG(f2.length) FROM Film f2 WHERE f2.rating = f1.rating)""")
    Page<Tuple> selectRatingCountsOfLongerThanRatingAverage(Pageable pageable);
}
