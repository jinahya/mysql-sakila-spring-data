package com.github.jinahya.mysql.sakila.data;

import com.github.jinahya.mysql.sakila.persistence.Address_;
import com.github.jinahya.mysql.sakila.persistence.City;
import com.github.jinahya.mysql.sakila.persistence.City_;
import com.github.jinahya.mysql.sakila.persistence.Country_;
import com.github.jinahya.mysql.sakila.persistence.Customer;
import com.github.jinahya.mysql.sakila.persistence.Customer_;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.domain.Specification;
import org.springframework.data.jpa.repository.Query;
import org.springframework.stereotype.Repository;

import java.util.List;
import java.util.Objects;

/**
 * A repository for {@link City}, the {@code city} table of the Sakila database.
 * <p>
 * The id is an {@link Integer} generated by the database ({@code GenerationType.IDENTITY}), so a newly constructed
 * city is saved with no id, and the id is set on the saved instance. A city has no business key:
 * {@link City#equals(Object)} compares ids, and only once they are assigned. The name is not unique; the sample data
 * holds two cities named {@code London}, in two countries. Every city is in a country ({@link City_#COUNTRY},
 * {@code NOT NULL}, loaded lazily). The addresses of a city are mapped as a collection, but its getter is not public
 * upstream, so a caller that needs them reads them through {@link AddressRepository}, with a {@link Specification}.
 * <p>
 * {@link _Repository} brings {@link org.springframework.data.jpa.repository.JpaSpecificationExecutor} for criteria
 * queries. Name the attributes through the generated static metamodel rather than by string, for example
 * {@code (root, query, builder) -> builder.equal(root.get(City_.city), city)}.
 * <p>
 * The methods below answer the exercises of upstream's {@code EXERCISES.asciidoc} on the {@code city} table, one
 * method per exercise, named in each method's javadoc by the exercise's id ({@code SAKILA-CITY-B-01}, ...), and by
 * its role: the book's pick, which every data module answers, or this module's own extra. A Basic method is plain: it
 * returns a {@link List}, in the order the exercise asks for, written in the query. An Intermediate or Advanced method
 * takes a {@link Pageable}, the page and the sort, and returns a {@link Page}, so the order the exercise asks for, and
 * its {@code LIMIT}, are the caller's {@code PageRequest}; each method's javadoc says which sort that is. An exercise
 * that shows rows is a {@code default} method, {@code list...}, which builds a {@link Specification} with the Criteria
 * API and runs it through {@link org.springframework.data.jpa.repository.JpaSpecificationExecutor}. An exercise that
 * shows columns, grouped and counted, cannot be a {@code Specification}, which only filters; such a method,
 * {@code select...}, declares its JPQL with {@link Query}, with a count query of its own since Spring Data cannot
 * derive one from a grouped select, and returns a projection, one of the interfaces declared here, which Spring Data
 * backs with the selected columns, each aliased with the name of the getter it feeds. Those aliases are what the
 * {@code Pageable} sorts by; an interface rather than a record, because Spring Data rewrites a record projection into
 * a constructor expression, which drops the aliases, and the sort with them.
 *
 * @see City
 * @see City_
 */
@Repository
public interface CityRepository
        extends _Repository<City, Integer> {

    // ----------------------------------------------------------------------------------------------------- exercises

    /**
     * A country, by id and name, and how many cities it has: a projection of {@link #selectCityCounts(Pageable)},
     * sortable by {@code countryId}, {@code country} and {@code cities}.
     */
    interface CountryCityCount {

        /**
         * Returns the id of the country.
         *
         * @return the id of the country.
         */
        Integer getCountryId();

        /**
         * Returns the name of the country.
         *
         * @return the name of the country.
         */
        String getCountry();

        /**
         * Returns the number of cities of the country.
         *
         * @return the number of cities.
         */
        long getCities();
    }

    /**
     * Finds the cities whose value of {@link City_#CITY} attribute starts with the specified prefix, ordered by that
     * name ({@code SAKILA-CITY-B-01}, the book's pick, which asks for the cities starting with {@code Q}, ordered by
     * {@link City_#CITY}).
     * <p>
     * The query is derived from the method name, its order too; Spring Data escapes the prefix and adds the trailing
     * {@code %}, so the caller passes the prefix alone. The comparison is the database's, which on the Sakila database
     * is case-insensitive, by the collation of the column.
     *
     * @param prefix the prefix of the {@link City_#CITY} attribute to match; must not be {@code null}.
     * @return a list of the cities whose name starts with {@code prefix}, by name; empty if there is none.
     */
    List<City> findAllByCityStartingWithOrderByCityAsc(String prefix);

    /**
     * Lists the cities of the country of the specified name ({@code SAKILA-CITY-I-01}, the book's pick, which asks
     * for the cities of {@code Canada}, ordered by {@link City_#CITY}).
     * <p>
     * A {@link Specification} of one equality, on the name of the city's {@link City_#COUNTRY}, a path through the
     * association which Hibernate renders as the exercise's join.
     *
     * @param country  the name of the country; must not be {@code null}.
     * @param pageable the page to return, and its sort; must not be {@code null}.
     * @return a page of the cities of the country named {@code country}.
     */
    default Page<City> listByCountry(final String country, final Pageable pageable) {
        Objects.requireNonNull(country, "country is null");
        Objects.requireNonNull(pageable, "pageable is null");
        final Specification<City> specification =
                (r, q, b) -> b.equal(r.get(City_.country).get(Country_.country), country);
        return findAll(specification, pageable);
    }

    /**
     * Selects the countries that have a city, with how many ({@code SAKILA-CITY-I-02}, this module's own extra, which
     * takes the first five by {@code cities} descending, then by {@code country}).
     * <p>
     * The cities are joined to their {@link City_#COUNTRY}, grouped by the country's id and name, and counted; the
     * count query counts the countries whose cities are not empty.
     *
     * @param pageable the page to return, and its sort, by {@code countryId}, {@code country} or {@code cities}; must
     *                 not be {@code null}.
     * @return a page of the countries that have a city, with their numbers of cities.
     */
    @Query(value = """
            SELECT co.countryId AS countryId, co.country AS country, COUNT(c) AS cities
            FROM City c
            JOIN c.country co
            GROUP BY co.countryId, co.country""",
           countQuery = """
                   SELECT COUNT(co)
                   FROM Country co
                   WHERE co.cities IS NOT EMPTY""")
    Page<CountryCityCount> selectCityCounts(Pageable pageable);

    /**
     * Lists the cities which are the only city of their country ({@code SAKILA-CITY-A-01}, the book's pick, which
     * takes the first ten by the name of the {@link City_#COUNTRY}, then by {@link City_#CITY_ID}).
     * <p>
     * A {@link Specification} of a correlated {@code NOT EXISTS}: no other city, by id, is in the same country. The
     * exercise shows the country's name beside the city; the city's country is lazy, so a caller that reads the name
     * does so in a transaction, or sorts by it, which joins it.
     *
     * @param pageable the page to return, and its sort, such as by {@code country.country}, then by {@code cityId};
     *                 must not be {@code null}.
     * @return a page of the cities which are the only city of their country.
     */
    default Page<City> listOnlyCityOfCountry(final Pageable pageable) {
        Objects.requireNonNull(pageable, "pageable is null");
        final Specification<City> specification = (r, q, b) -> {
            final var others = Objects.requireNonNull(q).subquery(Integer.class);
            final var o = others.from(City.class);
            others.select(o.get(City_.cityId))
                    .where(b.equal(o.get(City_.country), r.get(City_.country)),
                           b.notEqual(o.get(City_.cityId), r.get(City_.cityId)));
            return b.not(b.exists(others));
        };
        return findAll(specification, pageable);
    }

    /**
     * Lists the cities which have a customer, and whose customers are all inactive ({@code SAKILA-CITY-A-02}, this
     * module's own extra, which orders by {@link City_#CITY}, then by {@link City_#CITY_ID}).
     * <p>
     * A {@link Specification} of two correlated subqueries on {@link Customer}, through the customer's
     * {@link Customer_#ADDRESS} to its city: an {@code EXISTS} of any customer there, and a {@code NOT EXISTS} of an
     * active one. A city with no customer is not listed; it is not a city of inactive customers.
     *
     * @param pageable the page to return, and its sort; must not be {@code null}.
     * @return a page of the cities whose customers are all inactive.
     */
    default Page<City> listAllCustomersInactive(final Pageable pageable) {
        Objects.requireNonNull(pageable, "pageable is null");
        final Specification<City> specification = (r, q, b) -> {
            final var any = Objects.requireNonNull(q).subquery(Integer.class);
            final var c1 = any.from(Customer.class);
            any.select(c1.get(Customer_.customerId))
                    .where(b.equal(c1.get(Customer_.address).get(Address_.city), r));
            final var active = q.subquery(Integer.class);
            final var c2 = active.from(Customer.class);
            active.select(c2.get(Customer_.customerId))
                    .where(b.equal(c2.get(Customer_.address).get(Address_.city), r),
                           b.isTrue(c2.get(Customer_.active)));
            return b.and(b.exists(any), b.not(b.exists(active)));
        };
        return findAll(specification, pageable);
    }
}
