package com.github.jinahya.mysql.sakila.data;

import com.github.jinahya.mysql.sakila.persistence.Staff;
import com.github.jinahya.mysql.sakila.persistence.Staff_;
import com.github.jinahya.mysql.sakila.persistence.Store_;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.domain.Specification;
import org.springframework.data.jpa.repository.Query;
import org.springframework.stereotype.Repository;

import java.util.Objects;

/**
 * A repository for {@link Staff}, the {@code staff} table of the Sakila database.
 * <p>
 * The id is an {@link Integer} generated by the database ({@code GenerationType.IDENTITY}), so a newly constructed
 * staff member is saved with no id, and the id is set on the saved instance. A staff member has no business key:
 * {@link Staff#equals(Object)} compares ids, and only once they are assigned. Every staff member works at a store
 * ({@link Staff_#STORE}) and has an address ({@link Staff_#ADDRESS}), both {@code NOT NULL}; a store, in turn, names
 * its manager, a staff member, so the two tables refer to each other. The rentals and the payments a staff member
 * handled are not mapped on this side at all; a caller that needs them reads them through {@link RentalRepository}
 * or {@link PaymentRepository}, with a {@link Specification}.
 * <p>
 * {@link _Repository} brings {@link org.springframework.data.jpa.repository.JpaSpecificationExecutor} for criteria
 * queries. Name the attributes through the generated static metamodel rather than by string, for example
 * {@code (root, query, builder) -> builder.isTrue(root.get(Staff_.active))}.
 * <p>
 * The methods below answer the exercises of upstream's {@code EXERCISES_COORDINATES.asciidoc} on the {@code staff} table, one
 * method per exercise, named in each method's javadoc by the exercise's id ({@code SAKILA-STAFF-B-01}, ...), one or
 * two of each level. The exercises are context, not contract: each method takes a {@link Pageable}, the page and the
 * sort, and returns a {@link Page}, so the order the exercise asks for, and its {@code LIMIT}, are the caller's
 * {@code PageRequest}; each method's javadoc says which sort that is. An exercise that shows rows is a {@code default}
 * method, {@code list...}, which builds a {@link Specification} with the Criteria API and runs it through
 * {@link org.springframework.data.jpa.repository.JpaSpecificationExecutor}. An exercise that shows columns, grouped
 * and counted, cannot be a {@code Specification}, which only filters; such a method, {@code select...}, declares its
 * JPQL with {@link Query}, with a count query of its own since Spring Data cannot derive one from a grouped select,
 * and returns a projection, one of the interfaces declared here, which Spring Data backs with the selected columns,
 * each aliased with the name of the getter it feeds. Those aliases are what the {@code Pageable} sorts by; an
 * interface rather than a record, because Spring Data rewrites a record projection into a constructor expression,
 * which drops the aliases, and the sort with them.
 *
 * @see Staff
 * @see Staff_
 */
@Repository
public interface StaffRepository
        extends _Repository<Staff, Integer> {

    // ----------------------------------------------------------------------------------------------------- exercises

    /**
     * A staff member, by id and first name, and how many rentals the staff member handled: a projection of
     * {@link #selectRentalCounts(Pageable)}, sortable by {@code staffId}, {@code firstName} and {@code rentals}.
     */
    interface StaffRentalCount {

        /**
         * Returns the id of the staff member.
         *
         * @return the id of the staff member.
         */
        Integer getStaffId();

        /**
         * Returns the first name of the staff member.
         *
         * @return the first name of the staff member.
         */
        String getFirstName();

        /**
         * Returns the number of rentals the staff member handled.
         *
         * @return the number of rentals.
         */
        long getRentals();
    }

    /**
     * Lists every staff member, with the store they work at ({@code SAKILA-STAFF-B-01}, which orders by
     * {@link Staff_#STAFF_ID}).
     * <p>
     * A {@link Specification} with no predicate, which fetches the {@link Staff_#STORE} along with each staff member,
     * so that the store, lazy otherwise, is loaded by the same select and can be read once the page is detached. The
     * fetch is skipped for the count query Spring Data runs for the page, whose result type is {@link Long}: a count
     * fetches nothing.
     *
     * @param pageable the page to return, and its sort; must not be {@code null}.
     * @return a page of the staff members, each with its store loaded.
     */
    default Page<Staff> listWithStore(final Pageable pageable) {
        Objects.requireNonNull(pageable, "pageable is null");
        final Specification<Staff> specification = (r, q, b) -> {
            final var resultType = Objects.requireNonNull(q).getResultType();
            if (resultType != Long.class && resultType != long.class) {
                r.fetch(Staff_.store);
            }
            return b.conjunction();
        };
        return findAll(specification, pageable);
    }

    /**
     * Selects the staff members who handled at least one rental, with how many ({@code SAKILA-STAFF-I-01}, which
     * orders by {@code staffId}).
     * <p>
     * The staff member has no collection of rentals, so the query starts from {@code Rental}, joins its
     * {@code staff}, and groups by the staff member; a staff member with no rental is not in the page. The count query
     * counts the staff members for whom a rental exists.
     *
     * @param pageable the page to return, and its sort, by {@code staffId}, {@code firstName} or {@code rentals}; must
     *                 not be {@code null}.
     * @return a page of the staff members who handled a rental, with their numbers of rentals.
     */
    @Query(value = """
            SELECT s.staffId AS staffId, s.firstName AS firstName, COUNT(r) AS rentals
            FROM Rental r
            JOIN r.staff s
            GROUP BY s.staffId, s.firstName""",
           countQuery = """
                   SELECT COUNT(s)
                   FROM Staff s
                   WHERE EXISTS (SELECT r
                                 FROM Rental r
                                 WHERE r.staff = s)""")
    Page<StaffRentalCount> selectRentalCounts(Pageable pageable);

    /**
     * Lists the staff members who manage the very store they work at ({@code SAKILA-STAFF-I-02}, which orders by
     * {@link Staff_#STAFF_ID}).
     * <p>
     * A {@link Specification} with a join: the staff member's {@link Staff_#STORE} is joined, and its
     * {@link Store_#MANAGER_STAFF} compared with the staff member itself. The schema ties neither column to the other,
     * so the equality is the whole condition.
     *
     * @param pageable the page to return, and its sort; must not be {@code null}.
     * @return a page of the staff members who manage the store they work at.
     */
    default Page<Staff> listManagingOwnStore(final Pageable pageable) {
        Objects.requireNonNull(pageable, "pageable is null");
        final Specification<Staff> specification = (r, q, b) -> {
            final var store = r.join(Staff_.store);
            return b.equal(store.get(Store_.managerStaff), r);
        };
        return findAll(specification, pageable);
    }
}
