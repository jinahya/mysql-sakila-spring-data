package com.github.jinahya.mysql.sakila.data;

import com.github.jinahya.mysql.sakila.persistence.Staff;
import com.github.jinahya.mysql.sakila.persistence.Staff_;
import com.github.jinahya.mysql.sakila.persistence.Store_;
import jakarta.persistence.Tuple;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.domain.Specification;
import org.springframework.data.jpa.repository.EntityGraph;
import org.springframework.data.jpa.repository.Query;
import org.springframework.stereotype.Repository;

import java.util.List;
import java.util.Objects;
import java.util.stream.Stream;

/**
 * A repository for {@link Staff}, the {@code staff} table of the Sakila database.
 * <p>
 * The id is an {@link Integer} generated by the database ({@code GenerationType.IDENTITY}), so a newly constructed
 * staff member is saved with no id, and the id is set on the saved instance. A staff member has no business key:
 * {@link Staff#equals(Object)} compares ids, and only once they are assigned. Every staff member works at a store
 * ({@link Staff_#STORE}) and has an address ({@link Staff_#ADDRESS}), both {@code NOT NULL}; a store, in turn, names
 * its manager, a staff member, so the two tables refer to each other. The rentals and the payments a staff member
 * handled are not mapped on this side at all; a caller that needs them reads them through {@link RentalRepository}
 * or {@link PaymentRepository}, with a {@link Specification}.
 * <p>
 * {@link _Repository} brings {@link org.springframework.data.jpa.repository.JpaSpecificationExecutor} for criteria
 * queries. Name the attributes through the generated static metamodel rather than by string, for example
 * {@code (root, query, builder) -> builder.isTrue(root.get(Staff_.active))}.
 * <p>
 * The methods below answer the exercises of upstream's {@code EXERCISES.asciidoc} on the {@code staff} table, one
 * method per exercise, named in each method's javadoc by the exercise's id ({@code SAKILA-STAFF-B-01}, ...) and its
 * role: the book's pick, or this module's own extra. A Basic exercise is plain: its method takes no {@link Pageable},
 * the order the exercise asks for is written in the query, and it returns a {@link List} (the book's pick) or a
 * {@link Stream} (this module's own extra). An Intermediate or Advanced exercise takes a {@link Pageable}, the page and
 * the sort, and returns a {@link Page}, so the order the exercise asks for, and its {@code LIMIT}, are the caller's
 * {@code PageRequest}; each method's javadoc says which sort that is. An exercise that shows rows is a {@code default}
 * method, {@code list...}, which builds a {@link Specification} with the Criteria API and runs it through
 * {@link org.springframework.data.jpa.repository.JpaSpecificationExecutor}. An exercise that shows columns, grouped
 * and counted, cannot be a {@code Specification}, which only filters; such a method, {@code select...}, declares its
 * JPQL with {@link Query}, with a count query of its own since Spring Data cannot derive one from a grouped select.
 * Such a query selects entities, not their columns: a staff member is selected whole ({@code SELECT s AS staff}), and
 * grouped by itself ({@code GROUP BY s}) where the query groups; what is computed, a count, a sum, an expression, is a
 * column of its own beside it. A result that is a single entity is that entity; any other comes back as a
 * {@link jakarta.persistence.Tuple}, each element read by its alias, with its type
 * ({@code tuple.get("staff", Staff.class)}, {@code tuple.get("rentals", Long.class)}). The {@code Pageable} sorts a
 * computed column by its alias ({@code Sort.by(DESC, "rentals")}), and an attribute of a selected entity by its path
 * from the query's identification variable ({@code Sort.by("s.staffId")}); each method's javadoc names its aliases
 * and identification variables. A query which groups by a staff member and a value, a day, selects the staff member
 * whole and the value beside it.
 *
 * @see Staff
 * @see Staff_
 */
@Repository
public interface StaffRepository
        extends _Repository<Staff, Integer> {

    // ----------------------------------------------------------------------------------------------------- exercises

    /**
     * Finds every staff member, with the store they work at ({@code SAKILA-STAFF-B-01}, the book's pick, which orders
     * by {@link Staff_#STAFF_ID}).
     * <p>
     * The query is derived from the method name, whose {@code OrderBy} is the exercise's order. The
     * {@link EntityGraph} fetches the {@link Staff_#STORE} along with each staff member, so that the store, lazy
     * otherwise, is loaded by the same select and can be read once the list is detached.
     *
     * @return a list of every staff member, by id, each with its store loaded; empty if there is none.
     */
    @EntityGraph(attributePaths = Staff.ATTRIBUTE_NAME_STORE)
    List<Staff> findAllByOrderByStaffIdAsc();

    /**
     * Finds the staff members who have no password, as a stream ({@code SAKILA-STAFF-B-02}, this module's own extra,
     * which orders by {@link Staff_#STAFF_ID}).
     * <p>
     * The query is derived from the method name: an {@code IS NULL} on {@link Staff_#PASSWORD}, and the exercise's
     * order.
     * <p>
     * A {@link Stream} reads the rows as they are consumed, over a result set that stays open until the stream is
     * closed, so close it, in a try-with-resources. It also has to be consumed inside a transaction the caller opened:
     * the transaction the repository opens for itself ends when this method returns, which would close the result set
     * under the stream, so Spring Data refuses a call that no transaction surrounds, with an
     * {@link org.springframework.dao.InvalidDataAccessApiUsageException}, before any query runs.
     *
     * @return a stream of the staff members whose password is {@code null}, by id, to be closed by the caller; empty
     *         if there is none.
     */
    Stream<Staff> findAllByPasswordIsNullOrderByStaffIdAsc();

    /**
     * Selects the staff members who handled at least one rental, with how many ({@code SAKILA-STAFF-I-01}, this
     * module's own extra, which orders by {@code s.staffId}).
     * <p>
     * The staff member has no collection of rentals, so the query starts from {@code Rental}, joins its
     * {@code staff}, and groups by the staff member itself, which selects the staff member whole; a staff member with
     * no rental is not in the page. The count query counts the staff members for whom a rental exists.
     *
     * @param pageable the page to return, and its sort, by {@code rentals}, or by an attribute of the staff member
     *                 through {@code s} ({@code s.staffId}, {@code s.firstName}, ...); must not be {@code null}.
     * @return a page of the staff members who handled a rental, with their numbers of rentals, each a tuple of
     *         {@code staff} ({@link Staff}) and {@code rentals} ({@link Long}).
     */
    @Query(value = """
            SELECT s AS staff, COUNT(r) AS rentals
            FROM Rental r
            JOIN r.staff s
            GROUP BY s""",
           countQuery = """
                   SELECT COUNT(s)
                   FROM Staff s
                   WHERE EXISTS (SELECT r
                                 FROM Rental r
                                 WHERE r.staff = s)""")
    Page<Tuple> selectRentalCounts(Pageable pageable);

    /**
     * Lists the staff members who manage the very store they work at ({@code SAKILA-STAFF-I-02}, the book's pick,
     * which orders by {@link Staff_#STAFF_ID}).
     * <p>
     * A {@link Specification} with a join: the staff member's {@link Staff_#STORE} is joined, and its
     * {@link Store_#MANAGER_STAFF} compared with the staff member itself. The schema ties neither column to the other,
     * so the equality is the whole condition.
     *
     * @param pageable the page to return, and its sort; must not be {@code null}.
     * @return a page of the staff members who manage the store they work at.
     */
    default Page<Staff> listManagingOwnStore(final Pageable pageable) {
        Objects.requireNonNull(pageable, "pageable is null");
        final Specification<Staff> specification = (r, q, b) -> {
            final var store = r.join(Staff_.store);
            return b.equal(store.get(Store_.managerStaff), r);
        };
        return findAll(specification, pageable);
    }

    /**
     * Selects, for each staff member, the day on which the staff member took the most, with how many payments and
     * how much ({@code SAKILA-STAFF-A-01}, the book's pick, which orders by {@code s.staffId}).
     * <p>
     * The payments are grouped by the staff member itself, selected whole, and by day, the date part of
     * {@code paymentDate}, and a group is kept by a {@code HAVING} when its sum is not less than {@code ALL} the sums
     * of that staff member's other days, a correlated subquery; JPQL has no window function to rank the days with. Two days tied for the most would both be
     * kept; the sample data has no such tie. The count query counts the groups the same {@code HAVING} keeps, through
     * the smallest payment id of each, since Spring Data cannot derive a count from a grouped select.
     *
     * @param pageable the page to return, and its sort, by {@code paymentDay}, {@code payments} or {@code total}, or
     *                 by an attribute of the staff member through {@code s} ({@code s.staffId}, ...); must not be
     *                 {@code null}.
     * @return a page of the staff members' best days, each a tuple of {@code staff} ({@link Staff}),
     *         {@code paymentDay} ({@link java.time.LocalDate}), {@code payments} ({@link Long}) and {@code total}
     *         ({@link java.math.BigDecimal}).
     */
    @Query(value = """
            SELECT s AS staff, EXTRACT(DATE FROM p.paymentDate) AS paymentDay, COUNT(p) AS payments,
                   SUM(p.amount) AS total
            FROM Payment p
            JOIN p.staff s
            GROUP BY s, EXTRACT(DATE FROM p.paymentDate)
            HAVING SUM(p.amount) >= ALL (SELECT SUM(p2.amount)
                                         FROM Payment p2
                                         WHERE p2.staff.staffId = s.staffId
                                         GROUP BY EXTRACT(DATE FROM p2.paymentDate))""",
           countQuery = """
                   SELECT COUNT(p)
                   FROM Payment p
                   WHERE p.paymentId IN (SELECT MIN(p3.paymentId)
                                         FROM Payment p3
                                         JOIN p3.staff s3
                                         GROUP BY s3, EXTRACT(DATE FROM p3.paymentDate)
                                         HAVING SUM(p3.amount) >= ALL (SELECT SUM(p2.amount)
                                                                       FROM Payment p2
                                                                       WHERE p2.staff.staffId = s3.staffId
                                                                       GROUP BY EXTRACT(DATE FROM p2.paymentDate)))""")
    Page<Tuple> selectBestDays(Pageable pageable);
}
